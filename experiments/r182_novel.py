"""R-182 NOVEL branch: a persistence/hysteresis gate for `route_ewma_base`,
targeting the transition-doubling mechanism the pre-registration diagnosed
on inner-train.

**Relationship to the shared pre-registration.** `experiments/r182_shared.py`
(frozen, imported here UNEDITED) measured that a plain gated constant/EWMA
BASE split genuinely fixes the cost-ratio problem that killed R-145/151/154
(0.430 at BASE=0.25, 0.40% tier, vs R-154's 0.931), but every candidate
nonetheless shows a NEGATIVE `d_sharpe` point estimate on inner-train. The
named mechanism: `route_ewma_base`'s own `target[i] > 0` on/off gate forces
BOTH legs to fire simultaneously at every one of v4's own entry/exit
transitions (spot `0 -> BASE`/`BASE -> 0`, futures `0 -> target-BASE`/
`target-BASE -> 0`), concentrated exactly on the bars this project's own
N~3 diagnosis says carry most of v4's edge.

**This branch's mechanism, one sentence.** Replace `route_ewma_base`'s
`in_market = target > 0` on/off gate with a PERSISTENCE/HYSTERESIS gate:
the spot base stays "on" as long as v4 has been in-market (`target > 0`)
at ANY point within a trailing window of `H` days, turning off only after
a sustained absence longer than `H` -- so a brief in/out excursion (the
kind concentrated at transitions) no longer forces a simultaneous two-leg
move, while a genuinely extended flat period (longer than `H`) still
zeroes the spot leg out, so the B-03 synthetic-carry bug
`r182_shared.py` already found and fixed for the plain gate is not
reintroduced. `H` is swept over `{1, 3, 7, 14}` calendar days, exactly as
frozen in `experiments/r182_direction.md`'s Step 3 novel-branch section.

**Everything else (BASE level, EWMA halflife, degenerate-equivalence
convention, broker mechanics, fee tiers, decision thresholds) is
inherited from `r182_shared.py` unedited.** This file adds exactly one
new function, `route_ewma_hysteresis_base`, and the reporting/diagnostic
code the frozen falsification test and promotion bar require. It does
not modify, monkeypatch, or duplicate any line of `r182_shared.py`.

**EWMA halflife choice (a detail the frozen brief leaves to this branch,
since it only froze the `H` sweep).** Held fixed at `halflife_days=180`
for every `H`, so the only thing that varies across the sweep is the gate
mechanism this branch is testing, not a second, entangled parameter.
`180d` is one of the three halflives `r182_shared.py`'s own
`_liquidation_safety_scan` already self-tested for `route_ewma_base`
(60/180/365d, zero liquidations in every cell) -- picked as the middle of
that already-vetted set, not tuned against any inner-validation number
here.

**Primary-H selection rule (frozen in THIS file before inner-validation
results are computed, since `r182_direction.md` names "median-selected"
but does not spell out the tie-break for an even-sized sweep).** Rank the
4 `H` candidates by `d_sharpe` point estimate (hybrid vs plain futures
v4, inner-validation), AVERAGED across both fee tiers, ascending. The
primary is the lower of the two middle-ranked candidates (0-indexed
position 1 of 4 sorted ascending -- the "lower-median"), never the
best-performing `H`. This is a deliberate anti-cherry-pick rule, not a
result-dependent choice: it is fixed by `_select_primary_h()` below,
which runs before any interpretation of the numbers it ranks.

**Co-firing diagnostic, defined precisely (since the frozen falsification
test names it but not its exact bar-level definition).** A
target-zero-crossing bar is any bar `i` where `target` crosses zero
(entry: `target[i-1] <= 0 < target[i]`; exit: `target[i-1] > 0 >=
target[i]`). "Fires" means a REAL broker fill, not merely a nonzero
route-array delta: a first implementation of this diagnostic used a
naive `|delta| > 1e-9` threshold on the raw `RouteFn` arrays and found it
badly overcounts for the hysteresis route specifically -- while the gate
is held "on" through a brief excursion, the underlying EWMA keeps
decaying by a genuine but ECONOMICALLY MEANINGLESS ~1e-6-scale amount
every bar (median observed magnitude 3.07e-6 vs a real base-level jump's
0.18-0.27), which the real broker's 5% `REBALANCE_DEADBAND` would never
actually execute as an order -- confirmed by direct inspection before
freezing this definition (see git history / session log for the probe).
So this diagnostic instead runs `SignedHybridBroker` (imported unedited
from `r182_shared.py`) through its OWN real per-bar loop -- reproduced
here bar-for-bar identically to `run_signed_hybrid_backtest` (same
pending-fills-at-next-open, same funding-bucket construction), the one
piece of bookkeeping that function does not itself expose being which
bar's ROUTING DECISION a given fill traces back to -- and asks, for the
pending order generated by each target-zero-crossing bar's routing
decision: did `fills_spot` AND `fills_fut` both actually increment when
that order executed, and did the two legs' intended deltas (from the
route arrays, which is what `SignedHybridBroker._execute_leg`'s
direction is a function of) share a sign. This is the true,
deadband-and-min-notional-aware answer, not a proxy. Computed on
inner-validation bars only (the warmup prefix used to seed the causal
EWMA/gate is excluded), for BOTH the hysteresis route (this branch) and
the plain-gate `route_ewma_base` (`r182_shared.py`'s own existing route
builder, same halflife=180d) as the required comparison baseline.
"""

