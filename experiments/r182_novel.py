def eth_mechanism_check(h: float) -> dict:
    """Promotion-bar clause 4: `spot_frac + fut_frac == target` to
    floating tolerance, no lookahead/liquidation bug, on ETH
    (funding-free). ETH is never the dollar-savings gate (no ETH
    perpetual funding series is committed anywhere in this repo -- the
    same ceiling `r182_shared.py`/`r145_shared.py` disclose).
    """
    eth_df, eth_funding, eth_label = load_eth()

    def rb(frame: pd.DataFrame) -> RouteFn:
        return route_ewma_hysteresis_base(compute_target(frame), EWMA_HALFLIFE_DAYS, h)

    hybrid = run_signed_hybrid_backtest(eth_df, rb, spot_market(), fut_market(),
                                        funding=eth_funding, start=INNER_VAL_START, end=INNER_VAL_END)

    target, index, pre = _window_target(eth_df, INNER_VAL_START, INNER_VAL_END)
    route = route_ewma_hysteresis_base(target, EWMA_HALFLIFE_DAYS, h)
    sum_diff = float(np.abs((route.spot_frac + route.fut_frac) - target)[pre:].max())
    return {"h": h, "sum_diff": sum_diff, "liquidated": hybrid.liquidated, "label": eth_label}


