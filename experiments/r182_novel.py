# ------------------------------------------------------------------ gate

def _hysteresis_gate(target: np.ndarray, h_days: float) -> np.ndarray:
    """True at bar `i` iff `target > 0` at ANY point in `[i - h_bars, i]`
    (a trailing window of `H` days, `H` converted to bars at the fixed
    288-bars/day 5m convention `route_ewma_base` itself uses). Fully
    vectorized via a running "last True index" cummax -- causal by
    construction (bar `i` only ever looks at `target[0..i]`), no
    additional shift needed, matching `route_ewma_base`'s own docstring
    reasoning that `target[i]` is already causal.

    Degenerate check: `h_days=0` gives `h_bars=0`, so the window
    collapses to `[i, i]` -- i.e., this reduces EXACTLY to
    `target[i] > 0`, `route_ewma_base`'s own plain gate. Verified in
    `_degenerate_h0_check()`.
    """
    in_mkt_raw = target > 0.0
    h_bars = int(round(h_days * BARS_PER_DAY))
    idx = np.arange(len(target))
    true_idx = np.where(in_mkt_raw, idx, -1)
    last_true = np.maximum.accumulate(true_idx)
    return (last_true >= 0) & (idx - last_true <= h_bars)


def route_ewma_hysteresis_base(target: np.ndarray, halflife_days: float,
                               h_days: float) -> RouteFn:
    """`r182_shared.route_ewma_base`, with its `target[i] > 0` on/off gate
    replaced by `_hysteresis_gate`. The EWMA computation itself (the BASE
    level) is copied verbatim from `route_ewma_base` -- only the boolean
    gate array changes.
    """
    halflife_bars = halflife_days * BARS_PER_DAY
    ewma = pd.Series(target).ewm(halflife=halflife_bars, adjust=False).mean().to_numpy()
    ewma = np.clip(ewma, 0.0, None)
    gate = _hysteresis_gate(target, h_days)
    spot = np.where(gate, ewma, 0.0)
    fut = target - spot
    return RouteFn(spot, fut)


# ------------------------------------------------------- self-checks (own)

def _degenerate_h0_check(df: pd.DataFrame, funding: pd.Series | None) -> None:
    """`route_ewma_hysteresis_base(..., h_days=0)` must reproduce
    `route_ewma_base` exactly -- confirms the hysteresis machinery
    collapses correctly to the mechanism it is a generalization of.
    """
    lo = int(df.index.searchsorted(INNER_VAL_START))
    hi = int(df.index.searchsorted(INNER_VAL_END, side="right"))
    warmup = KellyRegimeV4().warmup
    pre = prefix_bars(df, lo, warmup)
    frame = df.iloc[lo - pre: hi]
    target = compute_target(frame)

    plain = route_ewma_base(target, EWMA_HALFLIFE_DAYS)
    hyst0 = route_ewma_hysteresis_base(target, EWMA_HALFLIFE_DAYS, 0.0)
    spot_diff = float(np.abs(plain.spot_frac - hyst0.spot_frac).max())
    fut_diff = float(np.abs(plain.fut_frac - hyst0.fut_frac).max())
    print(f"[H=0 degeneracy] max|spot diff|={spot_diff:.3e} max|fut diff|={fut_diff:.3e}")
    assert spot_diff < 1e-12, f"H=0 hysteresis diverges from route_ewma_base: {spot_diff:.3e}"
    assert fut_diff < 1e-12, f"H=0 hysteresis diverges from route_ewma_base: {fut_diff:.3e}"


