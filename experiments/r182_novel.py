# --------------------------------------------------------- B-03 re-check

def _window_target(df: pd.DataFrame, start: str, end: str) -> tuple[np.ndarray, pd.DatetimeIndex, int]:
    """Returns `(target, frame.index, prefix)` for `[start, end]`, `prefix`
    being the count of warmup-only bars at the head of the returned arrays
    (mirrors `run_signed_hybrid_backtest`'s own slicing exactly, so
    diagnostics computed here line up bar-for-bar with what the backtest
    actually sees and reports).
    """
    warmup = KellyRegimeV4().warmup
    lo = int(df.index.searchsorted(start))
    hi = int(df.index.searchsorted(end, side="right"))
    pre = prefix_bars(df, lo, warmup)
    frame = df.iloc[lo - pre: hi]
    return compute_target(frame), frame.index, pre


def _longest_flat_run(target: np.ndarray) -> tuple[int, int]:
    """Returns `(start_idx, length_bars)` of the longest consecutive run
    of `target == 0`.
    """
    flat = target <= 0.0
    best_start, best_len = 0, 0
    cur_start, cur_len = None, 0
    for i, f in enumerate(flat):
        if f:
            if cur_start is None:
                cur_start = i
            cur_len += 1
            if cur_len > best_len:
                best_start, best_len = cur_start, cur_len
        else:
            cur_start, cur_len = None, 0
    return best_start, best_len


def _b03_check(df: pd.DataFrame, funding: pd.Series | None) -> dict:
    """Confirms, for every swept `H`, that the spot leg reaches EXACTLY
    zero at some point during the longest genuine flat stretch in BOTH
    inner-train and inner-validation -- i.e. the hysteresis gate still
    turns off after a sustained absence, so B-03's synthetic-carry bug
    (already found and fixed for the plain gate in `r182_shared.py`) is
    not reintroduced by widening the gate's tolerance for brief
    excursions.
    """
    report: dict = {}
    windows = [("inner-train", "2017-01-01", INNER_TRAIN_END),
               ("inner-validation", INNER_VAL_START, INNER_VAL_END)]
    for label, start, end in windows:
        target, index, pre = _window_target(df, start, end)
        # restrict the flat-run search to the reported (post-warmup) window
        t_reported = target[pre:]
        idx_reported = index[pre:]
        start_i, length = _longest_flat_run(t_reported)
        flat_start_ts = idx_reported[start_i]
        flat_end_ts = idx_reported[min(start_i + length - 1, len(idx_reported) - 1)]
        flat_days = length / BARS_PER_DAY
        print(f"\n[B-03 check, {label}] longest flat (target<=0) run: {flat_start_ts} -> "
              f"{flat_end_ts} ({length:,} bars, {flat_days:.1f} days)")
        report[label] = {"flat_days": flat_days, "per_H": {}}
        for h in H_CANDIDATES:
            gate = _hysteresis_gate(target, h)
            gate_reported = gate[pre:]
            flat_slice = gate_reported[start_i: start_i + length]
            reaches_zero = bool((~flat_slice).any())
            if reaches_zero:
                off_at = int(np.argmax(~flat_slice))
                off_days = off_at / BARS_PER_DAY
            else:
                off_days = None
            print(f"    H={h:g}d: spot leg reaches exactly zero during this stretch: "
                  f"{reaches_zero} (turns off at day {off_days:.2f} of the stretch)"
                  if reaches_zero else
                  f"    H={h:g}d: spot leg reaches exactly zero during this stretch: {reaches_zero}")
            report[label]["per_H"][h] = {"reaches_zero": reaches_zero, "off_day": off_days}
            if flat_days > h:
                assert reaches_zero, (
                    f"B-03 REGRESSION: H={h}d gate never zeroes the spot leg during a "
                    f"{flat_days:.1f}-day flat stretch in {label} (longer than H)")
    return report


# --------------------------------------------------- co-firing diagnostic

def _run_with_fill_trace(df: pd.DataFrame, route_builder, spot_mkt, fut_mkt,
                         funding: pd.Series | None, start: str, end: str):
    """Reproduces `run_signed_hybrid_backtest`'s own per-bar loop
    bar-for-bar (same pending-fills-at-next-open discipline, same
    funding-bucket construction) using the SAME `SignedHybridBroker`
    class imported unedited from `r182_shared.py` -- the one thing that
    function does not itself expose: which ROUTING-DECISION bar a given
    fill traces back to. Returns `(spot_fired, fut_fired, route, index,
    prefix)`, where `spot_fired[i]`/`fut_fired[i]` are True iff the
    pending order generated by the routing decision AT bar `i` (comparing
    `route[i]` to `route[i-1]`, executed at bar `i+1`'s open) produced a
    REAL broker fill on that leg (i.e. cleared the real deadband/
    min-notional gates in `SignedHybridBroker._execute_leg`, not merely a
    nonzero route-array delta).
    """
    warmup = KellyRegimeV4().warmup
    lo = int(df.index.searchsorted(start))
    hi = int(df.index.searchsorted(end, side="right"))
    prefix = prefix_bars(df, lo, warmup)
    frame = df.iloc[lo - prefix: hi]
    n = len(frame)

    route = route_builder(frame)

    opens = frame["open"].to_numpy(dtype=float)
    highs = frame["high"].to_numpy(dtype=float)
    lows = frame["low"].to_numpy(dtype=float)
    closes = frame["close"].to_numpy(dtype=float)
    index = frame.index

    bar_funding = None
    if funding is not None and len(funding) and fut_mkt.pays_funding:
        rates = funding.sort_index()
        rates = rates[(rates.index >= index[0]) & (rates.index <= index[-1])]
        if len(rates):
            slot = index.searchsorted(rates.index, side="right") - 1
            bar_funding = {}
            for pos_i, rate in zip(slot, rates.to_numpy(dtype=float)):
                if pos_i >= 0:
                    bar_funding[int(pos_i)] = bar_funding.get(int(pos_i), 0.0) + float(rate)

    broker = SignedHybridBroker(spot=spot_mkt, fut=fut_mkt, start_balance=1_000.0)

    spot_fired = np.zeros(n, dtype=bool)
    fut_fired = np.zeros(n, dtype=bool)
    pending: tuple[float, float] | None = None
    pending_decision_bar: int | None = None

    for i in range(n):
        if pending is not None and not broker.dead:
            fs0, ff0 = broker.fills_spot, broker.fills_fut
            broker.fill(pending[0], pending[1], opens[i])
            if pending_decision_bar is not None:
                spot_fired[pending_decision_bar] = broker.fills_spot > fs0
                fut_fired[pending_decision_bar] = broker.fills_fut > ff0
        pending, pending_decision_bar = None, None

        broker.check_liquidation(opens[i], opens[i], opens[i])
        broker.check_liquidation(opens[i], highs[i], lows[i])

        if bar_funding is not None:
            rate = bar_funding.get(i)
            if rate is not None:
                broker.apply_funding(rate, closes[i])

        last_bar = i == n - 1
        if not broker.dead and not last_bar and i >= prefix:
            changed = (i == 0
                      or abs(route.spot_frac[i] - route.spot_frac[i - 1]) > 1e-9
                      or abs(route.fut_frac[i] - route.fut_frac[i - 1]) > 1e-9)
            if changed:
                pending = route(i)
                pending_decision_bar = i

    return spot_fired, fut_fired, route, index, prefix


def _cofiring_count(spot_fired: np.ndarray, fut_fired: np.ndarray, route: RouteFn,
                    target: np.ndarray, pre: int) -> int:
    """Count of target-zero-crossing bars (restricted to bars >= `pre`,
    i.e. the reported/non-warmup window) where the routing decision
    produced a REAL fill on BOTH legs (`spot_fired[i]` and
    `fut_fired[i]`), in the SAME direction (route-array delta signs
    agree). See module docstring for why "fires" means an actual broker
    fill, not a raw route-array delta.
    """
    n = len(target)
    count = 0
    for i in range(max(pre, 1), n):
        prev_t, cur_t = target[i - 1], target[i]
        entry = prev_t <= 0.0 < cur_t
        exit_ = prev_t > 0.0 >= cur_t
        if not (entry or exit_):
            continue
        if not (spot_fired[i] and fut_fired[i]):
            continue
        d_spot = route.spot_frac[i] - route.spot_frac[i - 1]
        d_fut = route.fut_frac[i] - route.fut_frac[i - 1]
        if np.sign(d_spot) == np.sign(d_fut) and d_spot != 0.0:
            count += 1
    return count


# ------------------------------------------------------------ exposure

def _exposure_stats(equity: pd.Series) -> dict:
    rets = equity.pct_change().dropna()
    return {
        "time_in_market": float((equity.diff().fillna(0.0) != 0.0).mean()),
        "ann_vol": float(rets.std() * np.sqrt(365.0 * 288.0)) if len(rets) else float("nan"),
    }


# ---------------------------------------------------------- primary-H rule

def _select_primary_h(dsharpe_by_h: dict[float, float]) -> float:
    """Frozen anti-cherry-pick rule -- see module docstring. Ranks the 4
    `H` candidates by `d_sharpe` point estimate (already averaged across
    fee tiers by the caller) ascending, and returns the lower of the two
    middle-ranked candidates.
    """
    ordered = sorted(H_CANDIDATES, key=lambda h: dsharpe_by_h[h])
    return ordered[len(ordered) // 2 - 1]


