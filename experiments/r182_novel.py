    """Same truncation-causality discipline `r182_shared.py`'s own
    self-test uses, run against this branch's own route builder
    (primary H).
    """
    h = H_CANDIDATES[0]

    def rb(frame: pd.DataFrame) -> RouteFn:
        return route_ewma_hysteresis_base(compute_target(frame), EWMA_HALFLIFE_DAYS, h)

    full = run_signed_hybrid_backtest(df, rb, spot_market(), fut_market(), funding=funding,
                                      start=INNER_VAL_START, end=INNER_VAL_END)
